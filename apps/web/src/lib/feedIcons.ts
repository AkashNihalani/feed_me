type Pick = { n: string; d: string };
const KEY = 'fm:feed-icons:v1';
let picks: Record<string, Pick> | null = null;
let version = 0;
const listeners = new Set<() => void>();

function load(): Record<string, Pick> {
  if (picks) return picks;
  if (typeof window === 'undefined') return {};
  try {
    picks = (JSON.parse(window.localStorage.getItem(KEY) || '{}') as Record<string, Pick>) || {};
  } catch {
    picks = {};
  }
  return picks;
}

// a drawing is only ever lines: nothing else is let through from what was kept
const SAFE = /^(?:<(?:path|circle|rect|line|polyline|polygon|ellipse)(?: [a-z0-9-]+="[^"<>]*")*\/>)*$/;

export function guessedIcon(title: string): string {
  const words = title.toLowerCase().split(/[^a-z]+/).filter(Boolean);
  return GUESS[title.trim().toLowerCase()] || words.map((word) => GUESS[word]).find(Boolean) || '';
}

// the name of the one it wears ('' for its letters)
export function feedIconName(id: string, title: string): string {
  const pick = load()[id];
  return pick ? pick.n : guessedIcon(title);
}

// its lines ('' for its letters)
export function feedIcon(id: string, title: string): string {
  const pick = load()[id];
  const drawn = pick ? pick.d : DRAWN[guessedIcon(title)] || '';
  return SAFE.test(drawn) ? drawn : '';
}

export function setFeedIcon(id: string, name: string, drawn: string) {
  picks = { ...load(), [id]: { n: name, d: drawn } };
  version += 1;
  try {
    window.localStorage.setItem(KEY, JSON.stringify(picks));
  } catch {
    // storage blocked: it holds until the app closes
  }
  listeners.forEach((listener) => listener());
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function useFeedIcon(id: string, title: string): string {
  useSyncExternalStore(subscribe, () => version, () => 0);
  // (the server draws the letters or the guess: what is kept is only on the device)
  return feedIcon(id, title);
}
